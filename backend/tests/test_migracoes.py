"""Migrações aplicadas no banco de teste: esquema igual aos modelos e regras do banco."""

import uuid

import pytest
from sqlalchemy import Engine, text
from sqlalchemy.exc import IntegrityError

from alembic import command
from alembic.config import Config
from tests.conftest import BACKEND_DIR

INSERIR_OCORRENCIA = text(
    "INSERT INTO ocorrencias (identificacao_id, titulo, descricao, categoria, latitude, longitude,"
    " status, prioridade, prioridade_pontuacao, prioridade_justificativa, ia_status)"
    " VALUES (:ident, 'Buraco de teste', 'Descrição de teste da migração', 'BURACO', -23.55, -46.63,"
    " 'ABERTA', 'BAIXA', 3, 'Teste', 'INDISPONIVEL')"
    " RETURNING id, origem, endereco, subprefeitura_codigo"
)
CONFIRMAR = text("INSERT INTO confirmacoes (ocorrencia_id, identificacao_id) VALUES (:o, :i)")


def _limpar(engine: Engine) -> None:
    with engine.begin() as conn:
        conn.execute(text("TRUNCATE confirmacoes, historico_status, ocorrencias, identificacoes RESTART IDENTITY CASCADE"))


def test_alembic_check_sem_diferencas(banco_migrado: Engine) -> None:
    # Lança AutogenerateDiffsDetected se modelos e migrações divergirem.
    command.check(Config(str(BACKEND_DIR / "alembic.ini")))


def test_origem_padrao_app_e_confirmacao_unica(banco_migrado: Engine) -> None:
    _limpar(banco_migrado)
    autor, outra = uuid.uuid4(), uuid.uuid4()
    with banco_migrado.begin() as conn:
        conn.execute(
            text("INSERT INTO identificacoes (id, apelido) VALUES (:a, 'Autor'), (:b, 'Outra pessoa')"),
            {"a": autor, "b": outra},
        )
        linha = conn.execute(INSERIR_OCORRENCIA, {"ident": autor}).one()
        assert (linha.origem, linha.endereco, linha.subprefeitura_codigo) == ("APP", None, None)
        conn.execute(CONFIRMAR, {"o": linha.id, "i": outra})

    with pytest.raises(IntegrityError), banco_migrado.begin() as conn:
        conn.execute(CONFIRMAR, {"o": linha.id, "i": outra})
    _limpar(banco_migrado)


def test_recalcular_subprefeituras_preenche_so_as_nulas(banco_migrado: Engine) -> None:
    from sqlalchemy.orm import Session

    from app.services.ocorrencias import recalcular_subprefeituras

    _limpar(banco_migrado)
    autor = uuid.uuid4()
    with banco_migrado.begin() as conn:
        conn.execute(text("INSERT INTO identificacoes (id, apelido) VALUES (:a, 'Autor')"), {"a": autor})
        na_se = conn.execute(INSERIR_OCORRENCIA, {"ident": autor}).one().id
        no_rio = conn.execute(INSERIR_OCORRENCIA, {"ident": autor}).one().id
        conn.execute(text("UPDATE ocorrencias SET latitude = -23.5503, longitude = -46.6340 WHERE id = :o"), {"o": na_se})
        conn.execute(text("UPDATE ocorrencias SET latitude = -22.9068, longitude = -43.1729 WHERE id = :o"), {"o": no_rio})

    with Session(banco_migrado) as db:
        assert recalcular_subprefeituras(db) == (1, 1)
        assert recalcular_subprefeituras(db) == (0, 1)  # idempotente: só tenta as que seguem nulas
        assert recalcular_subprefeituras(db, todas=True) == (1, 1)

    with banco_migrado.connect() as conn:
        linhas = conn.execute(text("SELECT id, subprefeitura_codigo FROM ocorrencias")).all()
    codigos = {linha.id: linha.subprefeitura_codigo for linha in linhas}
    assert codigos == {na_se: "09", no_rio: None}
    _limpar(banco_migrado)


def test_origem_fora_da_lista_e_rejeitada(banco_migrado: Engine) -> None:
    _limpar(banco_migrado)
    autor = uuid.uuid4()
    with banco_migrado.begin() as conn:
        conn.execute(text("INSERT INTO identificacoes (id, apelido) VALUES (:a, 'Autor')"), {"a": autor})
        oid = conn.execute(INSERIR_OCORRENCIA, {"ident": autor}).one().id
    with pytest.raises(IntegrityError), banco_migrado.begin() as conn:
        conn.execute(text("UPDATE ocorrencias SET origem = 'INVENTADA' WHERE id = :o"), {"o": oid})
    _limpar(banco_migrado)
